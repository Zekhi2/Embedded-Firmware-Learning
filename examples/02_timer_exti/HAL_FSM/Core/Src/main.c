/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_TIM3_Init();
  /* USER CODE BEGIN 2 */
  drv_timer_tick_init();  /* 仅 HAL_TIM_Base_Start_IT：MX_TIM3_Init 已由上方生成区完成 */
  LED_Init();
  KEY_Init();

  uint32_t led_last_tick = 0;
  uint32_t key_last_scan_tick = 0;
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
    uint32_t now = drv_timer_tick_get();

    /* 按键状态机周期扫描 */
    if ((uint32_t)(now - key_last_scan_tick) >= KEY_SCAN_PERIOD_MS)
    {
      key_last_scan_tick = now;
      key_event_t key_event = KEY_Process();

      switch (key_event)
      {
        case KEY_EVENT_SINGLE_CLICK:
        {
          /* 短按：翻转 LED，并重置闪烁节拍 */
          LED_Toggle();
          led_last_tick = now;
        }
        break;

        case KEY_EVENT_DOUBLE_CLICK:
        {
          /* 双击示例，可扩展 */
        }
        break;

        case KEY_EVENT_LONG_START:
        {
          /* 长按示例，可扩展 */
        }
        break;

        case KEY_EVENT_LONG_REPEAT:
        {
          /* 长按连发示例，可扩展 */
        }
        break;

        default:
        break;
      }
    }

    /* 非阻塞 LED 闪烁：500ms 一次 */
    if ((uint32_t)(now - led_last_tick) >= LED_BLINK_PERIOD_MS)
    {
      led_last_tick = now;
      LED_Toggle();
    }
  }
  /* USER CODE END 3 */
}

